import type { Workbook, Worksheet } from 'exceljs';

import { Employee } from '../models/team.model';
import { DailyActivityRow, ExportData, FailedSignIn } from '../models/report.model';
import { IDLE_GAP_MINUTES } from './day-activity';
import {
  CATEGORY_LABELS,
  buildDailyRows,
  buildFailureReport,
  countryName,
} from './sign-in-insights';

export interface ActivityExportInput {
  employees: Employee[];
  data: ExportData;
  /** Local calendar days covered, oldest first */
  days: Date[];
  generatedBy: string;
  workStartHour: number;
  workEndHour: number;
}

/** Shows a duration (in days, as Excel stores it) as "2 h 48 min". */
const DURATION_FORMAT = '[h] "h" mm "min"';

const COLORS = {
  headerFill: 'FF1F4FD1',
  headerText: 'FFFFFFFF',
  ink: 'FF172033',
  soft: 'FF5A6577',
  line: 'FFE3E8EC',
  fail: 'FFB42318',
  failFill: 'FFFDF3F2',
  amberFill: 'FFFDF6E7',
  amber: 'FF8A5A00',
  noSignInText: 'FF8A94A3',
};

/**
 * Builds the activity workbook and downloads it.
 * ExcelJS (about 1.4 MB) is loaded only when this runs.
 */
export async function downloadActivityWorkbook(input: ActivityExportInput): Promise<void> {
  const mod: any = await import('exceljs');
  const ExcelJS: typeof import('exceljs') = mod.default ?? mod;

  const wb = new ExcelJS.Workbook();
  wb.creator = input.generatedBy;
  wb.created = new Date();

  const first = input.days[0];
  const last = input.days[input.days.length - 1];
  const rangeEnd = new Date(last.getFullYear(), last.getMonth(), last.getDate() + 1);

  const daily = buildDailyRows(
    input.employees,
    input.data.interactive,
    input.data.background,
    input.days,
  );
  const report = buildFailureReport(input.data.interactive, first, rangeEnd);

  addSummarySheet(
    wb,
    input,
    daily,
    report.totalAttempts,
    report.suspiciousAttempts,
    report.homeCountries,
  );
  addDailySheet(wb, daily, input);
  addFailuresSheet(wb, report.failures);
  addCountrySheet(wb, report.byCountry);
  addIpSheet(wb, report.byIp);

  const buffer = await wb.xlsx.writeBuffer();
  const blob = new Blob([buffer], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });

  saveBlob(blob, `employee-activity_${fileDate(first)}_to_${fileDate(last)}.xlsx`);
}

// ---------- sheets ----------

function addSummarySheet(
  wb: Workbook,
  input: ActivityExportInput,
  daily: DailyActivityRow[],
  failedAttempts: number,
  suspiciousAttempts: number,
  homeCountries: string[],
): void {
  const ws = wb.addWorksheet('Summary', { properties: { tabColor: { argb: COLORS.headerFill } } });
  ws.columns = [{ width: 34 }, { width: 70 }];

  const first = input.days[0];
  const last = input.days[input.days.length - 1];
  const activeDays = daily.filter((r) => r.status === 'Active').length;
  const matchApp = input.data.mode === 'match-app';

  ws.addRow(['Employee activity report']).font = {
    bold: true,
    size: 16,
    color: { argb: COLORS.ink },
  };
  ws.addRow([]);

  const facts: [string, string | number][] = [
    ['Period', `${longDate(first)} to ${longDate(last)} (${input.days.length} days)`],
    [
      'Generated',
      `${longDate(new Date())}, ${new Date().toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' })}`,
    ],
    ['Generated by', input.generatedBy],
    [
      'Data',
      matchApp
        ? 'Interactive and background sign-ins (same as the app’s day view)'
        : 'Interactive sign-ins only (faster; No activity columns left blank)',
    ],
    ['Employees', input.employees.length],
    ['Employee-days with activity', activeDays],
    ['Failed sign-in attempts', failedAttempts],
    ['Of which look suspicious', suspiciousAttempts],
    ['Usual countries', homeCountries.map((c) => countryName(c)).join(', ') || 'Not enough data'],
  ];

  for (const [label, value] of facts) {
    const row = ws.addRow([label, value]);
    row.getCell(1).font = { bold: true, color: { argb: COLORS.soft } };
    row.getCell(2).alignment = { horizontal: 'left' };
  }

  ws.addRow([]);
  ws.addRow(['How to read this report']).font = { bold: true, size: 12 };

  const window = `${hourText(input.workStartHour)}–${hourText(input.workEndHour)}`;

  const notes = [
    [
      'Same as the app',
      `First activity, Last activity, Hours with activity and No activity are calculated exactly like the employee’s day view in the app, for ${window}.`,
    ],
    [
      'Windows sign-in',
      'First time that day the person signed in to their company Windows PC (Microsoft logs it as "Windows Sign In"). The most reliable sign of arriving at the desk. Can be before 6 AM.',
    ],
    [
      'First / Last activity',
      `First and last sign-in of any kind between ${window}${matchApp ? ', including background sign-ins made by open apps' : ''}. Microsoft doesn’t record sign-outs, so Last activity is the closest to "logout".`,
    ],
    [
      'First to last',
      'Time between First and Last activity. Not time worked: breaks and meetings are inside it.',
    ],
    [
      'Hours with activity',
      `How many of the ${input.workEndHour - input.workStartHour} hours between ${window} had at least one sign-in.`,
    ],
    [
      'No activity',
      matchApp
        ? `Total time in gaps of ${IDLE_GAP_MINUTES} minutes or more with no sign-in from any app, between First and Last activity. A strong sign of being away, but not keyboard-level idle time.`
        : 'Blank in this export: it needs background sign-ins. Export with "Match the app" to fill it.',
    ],
    [
      'Background sign-ins',
      'Apps renewing access on their own while open. They show the PC was on, not that the person was working.',
    ],
    [
      'Suspicious failures',
      'Wrong password, account locked, MFA denied, or an account that doesn’t exist. Interruptions such as the MFA prompt or "Stay signed in?" are normal and listed separately.',
    ],
    ['Unusual country', 'A failure from outside the usual countries listed above.'],
    [
      'Repeated',
      'The same IP or account failed many times in the period: a possible password-guessing attack.',
    ],
    ['Source', 'Microsoft Entra ID sign-in logs, kept by Microsoft for 30 days.'],
  ];

  if (input.data.truncatedDays.length) {
    notes.push([
      'Incomplete days',
      `More sign-ins than the safety limit on: ${input.data.truncatedDays.map(longDate).join(', ')}. Those days may be missing some background sign-ins.`,
    ]);
  }

  for (const [term, text] of notes) {
    const row = ws.addRow([term, text]);
    row.getCell(1).font = { bold: true };
    row.getCell(2).alignment = { wrapText: true, vertical: 'top' };
    row.alignment = { vertical: 'top' };
  }
}

function addDailySheet(wb: Workbook, rows: DailyActivityRow[], input: ActivityExportInput): void {
  const ws = wb.addWorksheet('Daily activity');
  const window = `${hourText(input.workStartHour)}–${hourText(input.workEndHour)}`;
  const matchApp = input.data.mode === 'match-app';

  ws.columns = [
    { header: 'Date', key: 'date', width: 13, style: { numFmt: 'dd mmm yyyy' } },
    { header: 'Day', key: 'day', width: 6 },
    { header: 'Employee', key: 'name', width: 28 },
    { header: 'Email', key: 'email', width: 34 },
    { header: 'Department', key: 'department', width: 22 },
    { header: 'Job title', key: 'jobTitle', width: 26 },
    { header: 'Status', key: 'status', width: 11 },
    { header: 'Windows sign-in', key: 'windows', width: 14, style: { numFmt: 'h:mm AM/PM' } },
    { header: 'First activity', key: 'first', width: 13, style: { numFmt: 'h:mm AM/PM' } },
    { header: 'Last activity', key: 'last', width: 13, style: { numFmt: 'h:mm AM/PM' } },
    { header: 'First to last', key: 'span', width: 15, style: { numFmt: DURATION_FORMAT } },
    {
      header: `Hours with activity (of ${input.workEndHour - input.workStartHour}, ${window})`,
      key: 'hours',
      width: 18,
    },
    { header: 'No activity', key: 'noActivity', width: 15, style: { numFmt: DURATION_FORMAT } },
    { header: 'Gaps', key: 'gaps', width: 7 },
    { header: 'Longest gap', key: 'longest', width: 15, style: { numFmt: DURATION_FORMAT } },
    { header: 'Sign-ins', key: 'signIns', width: 9 },
    { header: 'Background sign-ins', key: 'background', width: 13 },
    { header: 'Failed', key: 'failed', width: 8 },
    { header: 'Apps', key: 'apps', width: 40 },
    { header: 'Locations', key: 'locations', width: 28 },
    { header: 'IP addresses', key: 'ips', width: 26 },
    { header: 'Devices', key: 'devices', width: 32 },
  ];

  for (const r of rows) {
    const active = r.status === 'Active';

    const row = ws.addRow({
      date: excelDate(r.date),
      day: r.date.toLocaleDateString('en-GB', { weekday: 'short' }),
      name: r.name,
      email: r.email,
      department: r.department,
      jobTitle: r.jobTitle,
      status: r.status,
      windows: r.windowsSignIn ? excelDate(r.windowsSignIn) : null,
      first: r.firstActivity ? excelDate(r.firstActivity) : null,
      last: r.lastActivity ? excelDate(r.lastActivity) : null,
      span: active ? r.spanMinutes / 1440 : null,
      hours: active ? r.hoursWithActivity : null,
      noActivity: active && r.noActivityMinutes !== null ? r.noActivityMinutes / 1440 : null,
      gaps: active && r.gaps !== null ? r.gaps : null,
      longest: active && r.longestGapMinutes ? r.longestGapMinutes / 1440 : null,
      signIns: r.signIns,
      background: r.backgroundSignIns,
      failed: r.failed,
      apps: r.apps,
      locations: r.locations,
      ips: r.ipAddresses,
      devices: r.devices,
    });

    if (!active) {
      row.font = { color: { argb: COLORS.noSignInText } };
    }
    if (r.gaps) {
      for (const key of ['noActivity', 'gaps', 'longest']) {
        const cell = row.getCell(key);
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.amberFill } };
        cell.font = { bold: true, color: { argb: COLORS.amber } };
      }
    }
    if (r.failed > 0) {
      row.getCell('failed').font = { bold: true, color: { argb: COLORS.fail } };
    }
  }

  if (!matchApp) {
    // Make it obvious why these are empty
    for (const key of ['noActivity', 'gaps', 'longest', 'background']) {
      ws.getColumn(key).header = `${ws.getColumn(key).header} (needs "Match the app")`;
    }
  }

  styleTable(ws);
}

function addFailuresSheet(wb: Workbook, failures: FailedSignIn[]): void {
  const ws = wb.addWorksheet('Failed sign-ins', {
    properties: { tabColor: { argb: COLORS.fail } },
  });

  ws.columns = [
    {
      header: 'Date and time',
      key: 'time',
      width: 19,
      style: { numFmt: 'dd mmm yyyy h:mm AM/PM' },
    },
    { header: 'Account attempted', key: 'account', width: 34 },
    { header: 'Name', key: 'name', width: 24 },
    { header: 'Country', key: 'country', width: 18 },
    { header: 'City', key: 'city', width: 16 },
    { header: 'IP address', key: 'ip', width: 18 },
    { header: 'App', key: 'app', width: 28 },
    { header: 'What happened', key: 'category', width: 26 },
    { header: 'Error code', key: 'code', width: 11 },
    { header: 'Reason from Microsoft', key: 'reason', width: 50 },
    { header: 'Suspicious', key: 'suspicious', width: 11 },
    { header: 'Unusual country', key: 'unusual', width: 15 },
    { header: 'Repeated from IP', key: 'repeatedIp', width: 16 },
    { header: 'Repeated for account', key: 'repeatedAccount', width: 19 },
    { header: 'Browser / OS', key: 'client', width: 28 },
  ];

  const suspicious = new Set(['wrong-password', 'locked', 'mfa-denied', 'unknown-account']);

  for (const f of failures) {
    const isSuspicious = suspicious.has(f.category);

    const row = ws.addRow({
      time: excelDate(f.time),
      account: f.userPrincipalName,
      name: f.userName,
      country: f.country,
      city: f.city ?? '',
      ip: f.ipAddress ?? '',
      app: f.app,
      category: CATEGORY_LABELS[f.category],
      code: f.errorCode,
      reason: f.failureReason ?? '',
      suspicious: isSuspicious ? 'Yes' : 'No',
      unusual: f.unusualCountry ? 'Yes' : '',
      repeatedIp: f.repeatedFromIp ? 'Yes' : '',
      repeatedAccount: f.repeatedForAccount ? 'Yes' : '',
      client: [f.browser, f.operatingSystem].filter(Boolean).join(' on '),
    });

    if (f.repeatedFromIp || f.repeatedForAccount) {
      fillRow(row, COLORS.failFill);
    } else if (isSuspicious && f.unusualCountry) {
      fillRow(row, COLORS.amberFill);
    }
    if (isSuspicious) {
      row.getCell('category').font = { bold: true, color: { argb: COLORS.fail } };
    }
    if (f.unusualCountry) {
      row.getCell('country').font = { bold: true, color: { argb: COLORS.amber } };
    }
  }

  styleTable(ws);
}

function addCountrySheet(
  wb: Workbook,
  rows: { label: string; attempts: number; accounts: number; unusual?: boolean }[],
): void {
  const ws = wb.addWorksheet('Failures by country');

  ws.columns = [
    { header: 'Country', key: 'country', width: 26 },
    { header: 'Suspicious attempts', key: 'attempts', width: 20 },
    { header: 'Accounts targeted', key: 'accounts', width: 18 },
    { header: 'Unusual country', key: 'unusual', width: 16 },
  ];

  for (const r of rows) {
    const row = ws.addRow({
      country: r.label,
      attempts: r.attempts,
      accounts: r.accounts,
      unusual: r.unusual ? 'Yes' : '',
    });
    if (r.unusual) {
      fillRow(row, COLORS.amberFill);
    }
  }

  styleTable(ws);
}

function addIpSheet(
  wb: Workbook,
  rows: {
    ip: string;
    country: string;
    attempts: number;
    accounts: string[];
    lastSeen: Date;
    unusualCountry: boolean;
  }[],
): void {
  const ws = wb.addWorksheet('Failures by IP');

  ws.columns = [
    { header: 'IP address', key: 'ip', width: 20 },
    { header: 'Country', key: 'country', width: 20 },
    { header: 'Suspicious attempts', key: 'attempts', width: 20 },
    { header: 'Accounts targeted', key: 'count', width: 18 },
    { header: 'Last attempt', key: 'last', width: 20, style: { numFmt: 'dd mmm yyyy h:mm AM/PM' } },
    { header: 'Accounts', key: 'accounts', width: 70 },
  ];

  for (const r of rows) {
    const row = ws.addRow({
      ip: r.ip,
      country: r.country,
      attempts: r.attempts,
      count: r.accounts.length,
      last: excelDate(r.lastSeen),
      accounts: r.accounts.join(', '),
    });
    if (r.accounts.length >= 3 || r.attempts >= 10) {
      fillRow(row, COLORS.failFill);
    } else if (r.unusualCountry) {
      fillRow(row, COLORS.amberFill);
    }
  }

  styleTable(ws);
}

// ---------- styling helpers ----------

/** Blue header, frozen first row, filters on every column. */
function styleTable(ws: Worksheet): void {
  const header = ws.getRow(1);
  header.height = 30;
  header.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: COLORS.headerText } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: COLORS.headerFill } };
    cell.alignment = { vertical: 'middle', wrapText: true };
  });

  ws.views = [{ state: 'frozen', ySplit: 1 }];

  const columnCount = ws.columns?.length ?? 0;
  if (columnCount > 0) {
    ws.autoFilter = {
      from: { row: 1, column: 1 },
      to: { row: Math.max(1, ws.rowCount), column: columnCount },
    };
  }
}

function fillRow(row: import('exceljs').Row, argb: string): void {
  row.eachCell({ includeEmpty: true }, (cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb } };
  });
}

// ---------- small helpers ----------

/**
 * ExcelJS writes dates as UTC. Shift so Excel shows the same local
 * clock time the dashboard shows.
 */
function excelDate(d: Date): Date {
  return new Date(
    Date.UTC(
      d.getFullYear(),
      d.getMonth(),
      d.getDate(),
      d.getHours(),
      d.getMinutes(),
      d.getSeconds(),
    ),
  );
}

function saveBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}

function fileDate(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

function longDate(d: Date): string {
  return d.toLocaleDateString('en-GB', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

function hourText(hour: number): string {
  const h = hour % 12 === 0 ? 12 : hour % 12;
  return `${h} ${hour < 12 || hour === 24 ? 'AM' : 'PM'}`;
}
